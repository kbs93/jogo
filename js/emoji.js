let listaFiltrada = [];
let indicePaginacao = 0;
const ITENS_POR_PAGINA = 28;

export function inicializarCatalogo(termoFiltro = "") {
  listaFiltrada = Object.entries(bancoSvgEmojis).filter(([id]) => 
    id.toLowerCase().includes(termoFiltro.toLowerCase())
  );
  indicePaginacao = 0;
}

export function carregarMaisEmojis(container, idAtivo) {
  if (!container || indicePaginacao >= listaFiltrada.length) return;

  const proximoLote = listaFiltrada.slice(indicePaginacao, indicePaginacao + ITENS_POR_PAGINA);
  const fragmento = document.createDocumentFragment();

  proximoLote.forEach(([id, svgCode]) => {
    const botao = document.createElement("button");
    botao.type = "button";
    botao.className = `emoji-item ${id === idAtivo ? "ativo" : ""}`;
    botao.dataset.id = id;
    botao.innerHTML = `
      <div class="emoji-svg-wrap">${svgCode}</div>
      <span class="emoji-item-nome">${id.replace(/_/g, " ")}</span>
    `;
    fragmento.appendChild(botao);
  });

  container.appendChild(fragmento);
  indicePaginacao += ITENS_POR_PAGINA;
}